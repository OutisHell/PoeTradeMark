  var LANGS = ["ko", "en", "ja", "es", "fr", "de", "th", "ru", "pt", "tw"];
  function browserLanguage() {
    const base = (globalThis.navigator?.language || "en").toLowerCase().split("-")[0];
    if (base === "zh") return "tw";
    return LANGS.includes(base) ? base : "en";
  }
