# Build-time snapshot of the official trade filter catalogs.
$ErrorActionPreference = 'Stop'
$regions = [ordered]@{ en='www.pathofexile.com'; kr='poe.kakaogames.com'; tw='pathofexile.tw' }
foreach ($region in 'jp','de','fr','es','br','ru','th') { $regions[$region] = "$region.pathofexile.com" }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/harvest-trade-categories.ps1 from the official trade filter catalogs.')
$lines.Add('PTB.tradeCategoryLabels = {')
foreach ($game in 'poe1','poe2') {
    $api = if ($game -eq 'poe2') { 'trade2' } else { 'trade' }
    $lines.Add("  ${game}: {")
    foreach ($region in $regions.Keys) {
        $url = "https://$($regions[$region])/api/$api/data/filters"
        $catalog = Invoke-RestMethod $url -TimeoutSec 15
        $type = $catalog.result | Where-Object id -eq 'type_filters'
        $category = $type.filters | Where-Object id -eq 'category'
        $labels = [ordered]@{}
        foreach ($option in $category.option.options) {
            if ($option.id -and $option.text) { $labels[$option.id] = $option.text.Trim() }
        }
        if (!$labels.Count) { throw "Missing category labels at $url" }
        $lines.Add("    ${region}: $(ConvertTo-Json $labels -Compress),")
    }
    $lines.Add('  },')
}
$lines.Add('};')
$outputPath = Join-Path $PSScriptRoot '../extension/src/assets/trade-categories.js'
[IO.File]::WriteAllText($outputPath, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
